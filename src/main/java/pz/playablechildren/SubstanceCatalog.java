 public static boolean active(Set<String> mods,String id){return mods!=null&&(mods.contains(id)||mods.contains("\\"+id));}
 public static Kind kind(String fullType,String onEat,Set<String> mods){
  Kind result=Kind.NONE;
  for(Group group:GROUPS)if(active(mods,group.mod)&&group.items.contains(fullType)){
   if(group.kind==Kind.NARCOTIC)return Kind.NARCOTIC;
   result=group.kind;
  }
  return result;
 }
